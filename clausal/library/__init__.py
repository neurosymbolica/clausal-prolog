"""clausal.library -- the ``.seam`` facades a Clausal Prolog file imports as
``library(<lib>)``.

Clausal Prolog reaches Python only through ``.seam`` modules (operator
ruling, 2026-10-01).  Each ``<path>.seam`` here re-exports the predicates
and values of an engine Python module unchanged (``py/<lib>`` at
``<lib>``, ``countries/<j>`` at ``countries/<j>``), so::

    :- use_module(library(datetime), [date_add/3, days_between/3]).

replaces a direct ``use_module(py/datetime, ...)``.  The files are
GENERATED by ``clausal/tools/gen_library_facades.py``; do not edit them.
A name the native front end already knows as a library (``clpz``,
``lists``, ...) is never shadowed: those resolve first.
"""

from decimal import Decimal
from fractions import Fraction


def is_value(v) -> bool:
    """A VALUE a facade re-exports: a unit or currency (a units predicate
    with no arity), a quantity, or a number.  Not a function, class,
    module or sentinel -- those are the module's own machinery."""
    from clausal.modules.units import _UnitsPredicate  # noqa: PLC0415
    from clausal.terms import Quantity  # noqa: PLC0415
    if type(v) is bool:
        return False
    return isinstance(v, (_UnitsPredicate, Quantity, int, float, Decimal,
                          Fraction))
