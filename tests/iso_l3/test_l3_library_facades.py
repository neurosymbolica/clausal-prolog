def test_a_wrong_arity_against_a_facade_is_a_load_error(native,
                                                        clausal_prolog):
    # The facade is a seam module: its -import_from checks the indicator
    # when the importer runs (an ImportError naming the .pl line).
    with pytest.raises(ImportError) as ei:
        native.load("fac_arity", textwrap.dedent("""\
            :- module(fac_arity, []).
            :- use_module(library(datetime), [date_add/2]).
            :- end_module(fac_arity).
            """))
    msg = str(ei.value)
    assert "date_add/2" in msg and "date_add/3" in msg


# ── NO: Clausal Prolog importing a Python module directly ──


@pytest.mark.parametrize("frontend", ["native", "translator"])
@pytest.mark.parametrize("lib,pi", [("datetime", "date_add/3"),
                                    ("re", "match/2"), ("json", "parse/2")])
def test_clausal_prolog_refuses_a_py_import(native, frontend, lib, pi,
                                            clausal_prolog):
    name = f"fac_no_{lib}_{frontend}"
    msg = _refusal(native, name, f"""\
        :- module({name}, []).
        :- use_module(py/{lib}, [{pi}]).
        :- end_module({name}).
        """, frontend=frontend)
    assert "permission_error(access, python_module, py." + lib + ")" in msg
    assert f"library({lib})" in msg            # names the facade to use


def test_clausal_prolog_refuses_a_listless_py_import(native, clausal_prolog):
    msg = _refusal(native, "fac_no_all", """\
        :- module(fac_no_all, []).
        :- use_module(py/datetime).
        :- end_module(fac_no_all).
        """)
    assert "library(datetime)" in msg


def test_clausal_prolog_refuses_any_python_module(native, clausal_prolog):
    """Not only py/<lib>: any import target that is a Python file."""
