# ── units and currencies: values through a facade ──


def _money(native, ans, name, eu, units, **kw):
    mod = native.load(name, MONEY.format(name=name, eu=eu, units=units), **kw)
    return ans(mod, "hundred"), ans(mod, "secs")


@pytest.mark.parametrize("frontend", ["native"])
def test_currency_and_unit_values_through_their_facades(native, ans,
                                                        frontend,
                                                        monkeypatch):
    """(Native only: the translator front end does not lower
    constant_number_units/3 with a unit at all, on either surface.)"""
    # The ISO .pl surface, short names: the reference.
    want = _money(native, ans, f"fac_m_pl_{frontend}", "european_union",
                  "units", frontend=frontend)
    assert len(want[0]) == 1 and len(want[1]) == 1
    monkeypatch.setattr(_suffixes, "CLAUSAL_PROLOG_SUFFIXES", (".pl",))
    # YES: Clausal Prolog, the library(...) spelling ...
    assert _money(native, ans, f"fac_m_lib_{frontend}",
                  "library(countries/european_union)", "library(units)",
                  frontend=frontend) == want
    # ... and the short module names, which name the same facades.
    assert _money(native, ans, f"fac_m_short_{frontend}", "european_union",
                  "units", frontend=frontend) == want


@pytest.mark.parametrize("spec,imports,facade", [
    ("european_union", "euro", "clausal.library.countries.european_union"),
    ("library(countries/european_union)", "euro",
     "clausal.library.countries.european_union"),
    ("units", "second", "clausal.library.units"),
    ("date_time", "today/1", "clausal.library.datetime"),
])
def test_the_translator_imports_the_facade(spec, imports, facade):
    from clausal.tools.prolog_to_clausal import prolog_to_clausal
    out = prolog_to_clausal(f":- use_module({spec}, [{imports}]).\n",
                            surface="clausal_prolog")
    name = imports.split("/")[0]
    assert f"-import_from({facade}, [{name}])" in out, out


